CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE NULL
);

CREATE UNIQUE INDEX uk_users_email ON users (email);
CREATE INDEX idx_users_status ON users (status);
CREATE INDEX idx_users_deleted_at ON users (deleted_at);

CREATE TABLE journals (
    id VARCHAR(80) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    discipline VARCHAR(120) NOT NULL,
    description CLOB NOT NULL,
    issn_online VARCHAR(32) NOT NULL,
    publisher VARCHAR(255) NOT NULL,
    founded_year INTEGER NOT NULL,
    frequency VARCHAR(64) NOT NULL,
    aims_and_scope CLOB NOT NULL,
    editor_in_chief VARCHAR(255) NOT NULL,
    cover_storage_key VARCHAR(512) NULL,
    cover_content_type VARCHAR(128) NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE NULL
);

CREATE INDEX idx_journals_discipline ON journals (discipline);
CREATE INDEX idx_journals_created_at ON journals (created_at);
CREATE INDEX idx_journals_deleted_at ON journals (deleted_at);
CREATE INDEX idx_journals_name ON journals (name);

CREATE TABLE journal_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id VARCHAR(80) NOT NULL,
    volume INTEGER NOT NULL,
    issue INTEGER NOT NULL,
    published_at DATE NOT NULL,
    description CLOB NOT NULL,
    CONSTRAINT fk_journal_issues_journal FOREIGN KEY (journal_id) REFERENCES journals (id),
    CONSTRAINT uk_journal_issues_volume UNIQUE (journal_id, volume, issue)
);

CREATE INDEX idx_journal_issues_journal ON journal_issues (journal_id);
CREATE INDEX idx_journal_issues_published ON journal_issues (published_at);

CREATE TABLE journal_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL,
    title VARCHAR(500) NOT NULL,
    authors_json CLOB NOT NULL,
    abstract_text CLOB NOT NULL,
    keywords_json CLOB NOT NULL,
    pages VARCHAR(64) NULL,
    page_start INTEGER NULL,
    doi VARCHAR(255) NULL,
    article_type VARCHAR(64) NOT NULL,
    published_at DATE NOT NULL,
    citations INTEGER NOT NULL DEFAULT 0,
    open_access BOOLEAN NOT NULL DEFAULT TRUE,
    pdf_storage_key VARCHAR(512) NULL,
    pdf_original_filename VARCHAR(255) NULL,
    pdf_content_type VARCHAR(128) NULL,
    pdf_size_bytes BIGINT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT fk_journal_articles_issue FOREIGN KEY (issue_id) REFERENCES journal_issues (id),
    CONSTRAINT uk_journal_articles_doi UNIQUE (doi)
);

CREATE INDEX idx_journal_articles_issue ON journal_articles (issue_id);
CREATE INDEX idx_journal_articles_published ON journal_articles (published_at);
CREATE INDEX idx_journal_articles_type ON journal_articles (article_type);
CREATE INDEX idx_journal_articles_deleted ON journal_articles (deleted_at);
CREATE INDEX idx_journal_articles_page_start ON journal_articles (page_start);
CREATE INDEX idx_journal_articles_citations ON journal_articles (citations);

CREATE TABLE article_annotations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id BIGINT NOT NULL,
    author_user_id BIGINT NOT NULL,
    page_number INTEGER NOT NULL,
    selected_text CLOB NOT NULL,
    position_data CLOB NOT NULL,
    body CLOB NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_annotations_article FOREIGN KEY (article_id) REFERENCES journal_articles (id),
    CONSTRAINT fk_annotations_author FOREIGN KEY (author_user_id) REFERENCES users (id)
);

CREATE INDEX idx_annotations_article ON article_annotations (article_id);
CREATE INDEX idx_annotations_author ON article_annotations (author_user_id);
CREATE INDEX idx_annotations_status ON article_annotations (status);

CREATE TABLE article_annotation_replies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annotation_id BIGINT NOT NULL,
    author_user_id BIGINT NOT NULL,
    body CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_replies_annotation FOREIGN KEY (annotation_id) REFERENCES article_annotations (id),
    CONSTRAINT fk_replies_author FOREIGN KEY (author_user_id) REFERENCES users (id)
);

CREATE INDEX idx_replies_annotation ON article_annotation_replies (annotation_id);
